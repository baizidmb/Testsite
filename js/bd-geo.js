// Helper: All Divisions
function getDivisions() {
  return Object.keys(BD_GEO_DATA);
}

// Helper: Districts for a Division
function getDistrictsForDivision(division) {
  if (BD_GEO_DATA[division]) {
    return Object.keys(BD_GEO_DATA[division]);
  }
  return [];
}

// Helper: Upazilas for a District
function getUpazilasForDistrict(targetDistrict) {
  for (const districts of Object.values(BD_GEO_DATA)) {
    if (districts[targetDistrict]) {
      return districts[targetDistrict];
    }
  }
  return [];
}

// Flat list of all 64 districts
const ALL_DISTRICTS = [];
for (const [division, districts] of Object.entries(BD_GEO_DATA)) {
  for (const district of Object.keys(districts)) {
    ALL_DISTRICTS.push({ district, division });
  }
}

window.BD_GEO = {
  data: BD_GEO_DATA,
  icons: DIVISION_ICONS,
  districts: ALL_DISTRICTS,
  getDivisions: getDivisions,
  getDistricts: getDistrictsForDivision,
  getUpazilas: getUpazilasForDistrict
};

-- ========================================================
-- LittleNest BD: Supabase PostgreSQL Database Schema
-- Table: orders
-- Description: Centralized store orders table with Row Level Security (RLS)
-- ========================================================

-- 1. Create Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id VARCHAR(50) PRIMARY KEY,
    customer_name TEXT NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    full_address TEXT NOT NULL,
    division VARCHAR(100),
    district VARCHAR(100),
    upazila VARCHAR(100),
    detail_address TEXT,
    package_title TEXT NOT NULL,
    package_id VARCHAR(50),
    quantity INTEGER DEFAULT 1,
    selected_color VARCHAR(50),
    shipping_cost NUMERIC(10, 2) DEFAULT 0,
    total_price NUMERIC(10, 2) NOT NULL,
    order_date TEXT,
    timestamp BIGINT,
    status VARCHAR(50) DEFAULT 'New',
    cancel_reason TEXT DEFAULT '',
    return_reason TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Performance Indices
CREATE INDEX IF NOT EXISTS idx_orders_phone ON public.orders(customer_phone);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_timestamp ON public.orders(timestamp DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 4. RLS Policy: Anyone (Public Storefront) can INSERT orders
-- Allows checkout customers to place orders securely without creating an account
DROP POLICY IF EXISTS "Public storefront can place orders" ON public.orders;
CREATE POLICY "Public storefront can place orders"
    ON public.orders
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- 5. RLS Policy: Read Access
-- Allows storefront order verification and admin dashboard order fetching
DROP POLICY IF EXISTS "Allow read access for storefront and admin" ON public.orders;
CREATE POLICY "Allow read access for storefront and admin"
    ON public.orders
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- 6. RLS Policy: Update Access
-- Allows order status updates (e.g. Confirmed, Shipped, Delivered, Returned, Cancelled)
DROP POLICY IF EXISTS "Allow update access for order status" ON public.orders;
CREATE POLICY "Allow update access for order status"
    ON public.orders
    FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- 7. RLS Policy: Delete Access
-- Allows admin to clear test orders
DROP POLICY IF EXISTS "Allow delete access for admin" ON public.orders;
CREATE POLICY "Allow delete access for admin"
    ON public.orders
    FOR DELETE
    TO anon, authenticated
    USING (true);

-- 8. Enable Supabase Realtime for instant live order updates
-- When customers place orders, admin dashboard updates instantly via websocket
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'orders'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
  END IF;
END $$;

-- 9. Auto-update 'updated_at' trigger on modification
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_orders_updated_at ON public.orders;
CREATE TRIGGER set_orders_updated_at
    BEFORE UPDATE ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();
